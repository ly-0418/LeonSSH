//! Application wide state managed by Tauri.
//!
//! Holds the filesystem layout, the SQLite pool, the in-memory host key pins and
//! the registry of live terminal sessions.

use std::collections::HashMap;
use std::sync::atomic::{AtomicU64, Ordering};
use std::sync::Arc;

use sqlx::SqlitePool;
use tokio::sync::{mpsc, Mutex};

use crate::error::AppError;
use crate::forward::ForwardManager;
use crate::paths::Paths;
use crate::ssh::client::SharedHandle;
use crate::ssh::hostkey::KnownHosts;
use crate::terminal::registry::{SessionHandle, DEFAULT_CLOSE_TIMEOUT};
use russh_sftp::client::SftpSession;

/// Opaque session identifier generated by the backend (`s1`, `s2`, ...).
/// Kept as a string so it survives JSON round-trips without precision worries.
pub type SessionId = String;

#[derive(Clone, Default)]
pub struct SessionRegistry {
    sessions: Arc<Mutex<HashMap<SessionId, SessionHandle>>>,
    next_id: Arc<AtomicU64>,
}

impl SessionRegistry {
    pub fn new() -> Self {
        Self::default()
    }

    pub fn allocate_id(&self) -> SessionId {
        let n = self.next_id.fetch_add(1, Ordering::Relaxed) + 1;
        format!("s{n}")
    }

    pub async fn insert(&self, id: SessionId, handle: SessionHandle) {
        self.sessions.lock().await.insert(id, handle);
    }

    /// Clones the input sender so the caller can release the registry lock
    /// before awaiting the send itself.
    pub async fn input_sender(&self, id: &str) -> Result<mpsc::Sender<Vec<u8>>, AppError> {
        self.sessions
            .lock()
            .await
            .get(id)
            .map(|handle| handle.input_tx.clone())
            .ok_or_else(|| AppError::SessionNotFound(id.to_string()))
    }

    /// Resize is a control signal: it never touches the byte stream. A `watch`
    /// channel is used because only the latest size matters.
    pub async fn request_resize(&self, id: &str, cols: u16, rows: u16) -> Result<(), AppError> {
        let sessions = self.sessions.lock().await;
        let handle = sessions
            .get(id)
            .ok_or_else(|| AppError::SessionNotFound(id.to_string()))?;
        handle
            .resize_tx
            .send((cols, rows))
            .map_err(|_| AppError::SessionClosed(id.to_string()))
    }

    pub async fn remove(&self, id: &str) -> Option<SessionHandle> {
        self.sessions.lock().await.remove(id)
    }

    pub async fn count(&self) -> usize {
        self.sessions.lock().await.len()
    }

    /// Drains the registry and closes every session cooperatively.
    pub async fn close_all(&self) {
        let handles: Vec<SessionHandle> = {
            let mut sessions = self.sessions.lock().await;
            sessions.drain().map(|(_, handle)| handle).collect()
        };
        for handle in handles {
            let id = handle.id.clone();
            let outcome = handle.close(DEFAULT_CLOSE_TIMEOUT).await;
            tracing::info!(session = %id, ?outcome, "session closed during shutdown");
        }
    }
}

pub struct AppState {
    paths: Paths,
    db: SqlitePool,
    known_hosts: Arc<KnownHosts>,
    sessions: SessionRegistry,
    /// Live russh handles, keyed by terminal id — SFTP and port forwarding
    /// open extra channels on the *same* connection instead of reconnecting.
    connections: Mutex<HashMap<SessionId, SharedHandle>>,
    /// Cached SFTP subsystem sessions, keyed by terminal id.
    sftp: Mutex<HashMap<SessionId, Arc<SftpSession>>>,
    forward: ForwardManager,
}

impl AppState {
    pub fn new(paths: Paths, db: SqlitePool, known_hosts: Arc<KnownHosts>) -> Self {
        Self {
            paths,
            db,
            known_hosts,
            connections: Mutex::new(HashMap::new()),
            sftp: Mutex::new(HashMap::new()),
            forward: ForwardManager::new(),
            sessions: SessionRegistry::new(),
        }
    }

    pub fn paths(&self) -> &Paths {
        &self.paths
    }

    pub fn db(&self) -> &SqlitePool {
        &self.db
    }

    pub fn known_hosts(&self) -> &Arc<KnownHosts> {
        &self.known_hosts
    }

    pub fn forward_manager(&self) -> &ForwardManager {
        &self.forward
    }

    pub fn sessions(&self) -> &SessionRegistry {
        &self.sessions
    }

    // Thin delegations keep the command layer readable.

    pub fn allocate_session_id(&self) -> SessionId {
        self.sessions.allocate_id()
    }

    pub async fn insert_session(&self, id: SessionId, handle: SessionHandle) {
        self.sessions.insert(id, handle).await;
    }

    pub async fn input_sender(&self, id: &str) -> Result<mpsc::Sender<Vec<u8>>, AppError> {
        self.sessions.input_sender(id).await
    }

    pub async fn request_resize(&self, id: &str, cols: u16, rows: u16) -> Result<(), AppError> {
        self.sessions.request_resize(id, cols, rows).await
    }

    pub async fn remove_session(&self, id: &str) -> Option<SessionHandle> {
        self.sessions.remove(id).await
    }

    pub async fn session_count(&self) -> usize {
        self.sessions.count().await
    }

    // ------------------------------------------------------- ssh connections

    pub async fn register_connection(&self, terminal: SessionId, handle: SharedHandle) {
        self.connections.lock().await.insert(terminal, handle);
    }

    pub async fn connection(&self, terminal: &str) -> Result<SharedHandle, AppError> {
        self.connections
            .lock()
            .await
            .get(terminal)
            .cloned()
            .ok_or_else(|| AppError::SessionNotFound(terminal.to_string()))
    }

    pub async fn drop_connection(&self, terminal: &str) {
        self.connections.lock().await.remove(terminal);
    }

    // --------------------------------------------------------------- sftp

    pub async fn register_sftp(&self, terminal: SessionId, session: Arc<SftpSession>) {
        self.sftp.lock().await.insert(terminal, session);
    }

    pub async fn sftp(&self, terminal: &str) -> Result<Arc<SftpSession>, AppError> {
        self.sftp
            .lock()
            .await
            .get(terminal)
            .cloned()
            .ok_or_else(|| AppError::NotFound(format!("SFTP 会话未打开（terminal {terminal}）")))
    }

    pub async fn drop_sftp(&self, terminal: &str) {
        self.sftp.lock().await.remove(terminal);
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::paths::DataDirMode;
    use crate::storage::test_db;
    use std::path::PathBuf;
    use tokio::sync::watch;

    async fn test_state() -> AppState {
        let root = std::env::temp_dir().join(format!(
            "leonssh-state-{}",
            std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .unwrap()
                .as_nanos()
        ));
        let paths = Paths::build(PathBuf::from("C:/fake"), root, DataDirMode::InstallDir);
        let pool = test_db::open().await;
        let known = Arc::new(KnownHosts::load(pool.clone()).await.unwrap());
        AppState::new(paths, pool, known)
    }

    fn dummy_handle(id: &str) -> (SessionHandle, watch::Receiver<(u16, u16)>) {
        let (input_tx, _input_rx) = mpsc::channel::<Vec<u8>>(4);
        let (resize_tx, resize_rx) = watch::channel((80u16, 24u16));
        let (close_tx, _close_rx) = watch::channel(false);
        let join = tokio::spawn(async {
            tokio::time::sleep(std::time::Duration::from_secs(30)).await;
        });
        (
            SessionHandle::new(id.into(), input_tx, resize_tx, close_tx, join),
            resize_rx,
        )
    }

    #[tokio::test]
    async fn session_ids_are_unique_and_readable() {
        let state = test_state().await;
        assert_eq!(state.allocate_session_id(), "s1");
        assert_eq!(state.allocate_session_id(), "s2");
    }

    #[tokio::test]
    async fn unknown_session_yields_not_found() {
        let state = test_state().await;
        let err = state.input_sender("s99").await.unwrap_err();
        assert_eq!(err.code(), "session_not_found");
        let err = state.request_resize("s99", 80, 24).await.unwrap_err();
        assert_eq!(err.code(), "session_not_found");
    }

    #[tokio::test]
    async fn resize_reaches_the_session() {
        let state = test_state().await;
        let (handle, mut resize_rx) = dummy_handle("s1");
        state.insert_session("s1".into(), handle).await;

        state.request_resize("s1", 132, 43).await.unwrap();
        resize_rx.changed().await.unwrap();
        assert_eq!(*resize_rx.borrow_and_update(), (132, 43));
        assert_eq!(state.session_count().await, 1);
    }

    #[tokio::test]
    async fn registry_handle_is_shareable() {
        let state = test_state().await;
        let (handle, _rx) = dummy_handle("s7");
        state.insert_session("s7".into(), handle).await;

        let registry = state.sessions().clone();
        assert_eq!(registry.count().await, 1);
        registry.close_all().await;
        assert_eq!(registry.count().await, 0);
    }
}
